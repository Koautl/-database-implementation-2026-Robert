#!/usr/bin/env bash
set -Eeuo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUTPUT_SQL="$SCRIPT_DIR/Hair_Fix_Salon_Full_Build.sql"
LOG_DIR="$SCRIPT_DIR/logs"

# Ordered to satisfy object dependencies. These files all live beside build.sh.
BUILD_COMPONENTS=(
  "tables.sql"
  "keys.sql"
  "checks.sql"
  "indexes.sql"
  "views.sql"
  "procedures.sql"
  "sample_data.sql"
  "triggers.sql"
  "security.sql"
  "verify.sql"
)

usage() {
  printf '%s\n' \
    "Hair Fix Salon database build runner" \
    "" \
    "Usage:" \
    "  ./build.sh --assemble-only" \
    "  ./build.sh --execute [mysql client options]" \
    "  ./build.sh --help" \
    "" \
    "Examples:" \
    "  ./build.sh --assemble-only" \
    "  ./build.sh --execute -u root -p" \
    "  ./build.sh --execute --login-path=hairfix"
}

require_components() {
  local file
  local missing=0

  for file in "${BUILD_COMPONENTS[@]}"; do
    if [[ ! -f "$SCRIPT_DIR/$file" ]]; then
      printf 'ERROR: required schema component is missing: %s\n' "$file" >&2
      missing=1
    fi
  done

  if [[ "$missing" -ne 0 ]]; then
    printf '%s\n' 'Place build.sh inside the repository schema folder and try again.' >&2
    exit 1
  fi
}

append_component() {
  local file="$1"
  {
    printf '\n-- =====================================================================\n'
    printf '%s\n' "-- BUILD COMPONENT: $file"
    printf '%s\n' '-- ====================================================================='
    cat "$SCRIPT_DIR/$file"
    printf '\n'
  } >> "$OUTPUT_SQL"
}

assemble_build() {
  local file
  require_components

  {
    printf '%s\n' '-- Hair Fix Salon - Full Database Build'
    printf '%s\n' '-- Target platform: MySQL 8.x (not MariaDB)'
    printf '%s\n' '-- WARNING: tables.sql drops and recreates hair_fix_salon.'
    printf '%s\n' '-- Generated by schema/build.sh. Edit component files, not this file.'
  } > "$OUTPUT_SQL"

  for file in "${BUILD_COMPONENTS[@]}"; do
    append_component "$file"
  done

  printf 'Assembled: %s\n' "$OUTPUT_SQL"
}

execute_build() {
  local timestamp
  local log_file
  local status

  if ! command -v mysql >/dev/null 2>&1; then
    printf '%s\n' 'ERROR: the mysql command-line client was not found in PATH.' >&2
    exit 1
  fi

  assemble_build
  mkdir -p "$LOG_DIR"
  timestamp="$(date '+%Y%m%d_%H%M%S')"
  log_file="$LOG_DIR/build_${timestamp}.log"

  printf 'Executing with MySQL 8. Log: %s\n' "$log_file"
  if mysql --show-warnings --default-character-set=utf8mb4 "$@" \
      < "$OUTPUT_SQL" > "$log_file" 2>&1; then
    printf '%s\n' 'Build and verification completed successfully.'
    printf 'Review the verification output in: %s\n' "$log_file"
  else
    status=$?
    printf 'BUILD FAILED with exit code %s. Review: %s\n' \
      "$status" "$log_file" >&2
    exit "$status"
  fi
}

if [[ $# -lt 1 ]]; then
  usage
  exit 2
fi

mode="$1"
shift

case "$mode" in
  --assemble-only)
    if [[ $# -ne 0 ]]; then
      usage
      exit 2
    fi
    assemble_build
    ;;
  --execute)
    execute_build "$@"
    ;;
  --help|-h)
    usage
    ;;
  *)
    usage
    exit 2
    ;;
esac
